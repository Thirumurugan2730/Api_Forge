describe('Step 7: Spring Boot OpenAPI Import Suite', () => {

  describe('1. OpenAPI Document Validation & Version Enforcement', () => {
    it('should successfully parse valid OpenAPI 3.0.x and 3.1.x specifications', () => {
      const parsed30 = openApiParser.parseOpenApi(sampleSpringBootDoc);
      assert.equal(parsed30.apiInfo.title, 'Spring Boot Store Service');
      assert.equal(parsed30.apiInfo.version, '2.1.0');
      assert.equal(parsed30.servers.length, 2);
      assert.ok(parsed30.endpoints.length >= 7);

      const parsed31 = openApiParser.parseOpenApi({
        openapi: '3.1.0',
        info: { title: 'Modern Spring Boot 3.2', version: '1.0' },
        paths: {}
      });
      assert.equal(parsed31.apiInfo.title, 'Modern Spring Boot 3.2');
    });

    it('should reject Swagger 2.0 documents with an actionable explanation', () => {
      assert.throws(
        () => openApiParser.parseOpenApi({ swagger: '2.0', info: { title: 'Old API' }, paths: {} }),
        /Swagger 2.0.*not supported.*OpenAPI 3.x/i
      );
    });

    it('should reject missing or non-3.x openapi versions', () => {
      assert.throws(() => openApiParser.parseOpenApi({}), /Missing "openapi" version/i);
      assert.throws(() => openApiParser.parseOpenApi({ openapi: '4.0.0', paths: {} }), /Unsupported OpenAPI version/i);
      assert.throws(() => openApiParser.parseOpenApi(null), /Invalid OpenAPI document/i);
    });
  });

  describe('2. Endpoints Extraction & HTTP Methods Coverage', () => {
    it('should extract all 7 supported HTTP methods from paths', () => {
      const parsed = openApiParser.parseOpenApi(sampleSpringBootDoc);
      const methods = parsed.endpoints.map(e => e.method);

      assert.ok(methods.includes('GET'), 'Contains GET');
      assert.ok(methods.includes('POST'), 'Contains POST');
      assert.ok(methods.includes('PUT'), 'Contains PUT');
      assert.ok(methods.includes('PATCH'), 'Contains PATCH');
      assert.ok(methods.includes('DELETE'), 'Contains DELETE');
      assert.ok(methods.includes('HEAD'), 'Contains HEAD');
      assert.ok(methods.includes('OPTIONS'), 'Contains OPTIONS');
    });

    it('should extract path-level and operation-level parameters correctly', () => {
      const parsed = openApiParser.parseOpenApi(sampleSpringBootDoc);
      const getById = parsed.endpoints.find(e => e.operationId === 'getProductById');
      assert.ok(getById, 'Found getProductById');
      assert.equal(getById.pathParams.length, 1);
      assert.equal(getById.pathParams[0].name, 'id');
      assert.equal(getById.pathParams[0].required, true);

      const listEp = parsed.endpoints.find(e => e.operationId === 'listProducts');
      assert.ok(listEp);
      assert.equal(listEp.queryParams.length, 2);
      assert.equal(listEp.headerParams.length, 1);
      assert.equal(listEp.headerParams[0].name, 'X-Tenant-ID');
      assert.equal(listEp.headerParams[0].example, 'tenant-omega');
    });
  });

  describe('3. Local $ref Resolution & Request Body Synthesis', () => {
    it('should resolve nested $ref components and synthesize JSON request bodies', () => {
      const parsed = openApiParser.parseOpenApi(sampleSpringBootDoc);
      const createEp = parsed.endpoints.find(e => e.operationId === 'createProduct');
      assert.ok(createEp);
      assert.ok(createEp.body, 'Expected generated body for createProduct');

      const bodyObj = JSON.parse(createEp.body);
      assert.equal(bodyObj.sku, 'PROD-7788');
      assert.equal(bodyObj.name, 'Wireless Ergonomic Mouse');
      assert.equal(bodyObj.price, 49.99);
      assert.ok(Array.isArray(bodyObj.tags));
      assert.equal(bodyObj.tags[0], 'gadgets');
      assert.ok(bodyObj.vendor, 'VendorDTO was resolved');
      assert.equal(bodyObj.vendor.companyName, 'Apex Logistics');
      assert.equal(bodyObj.vendor.contactEmail, 'user@example.com');
    });

    it('should prioritize explicit examples over synthesized schemas', () => {
      const parsed = openApiParser.parseOpenApi(sampleSpringBootDoc);
      const updateEp = parsed.endpoints.find(e => e.operationId === 'updateProduct');
      assert.ok(updateEp);
      const parsedBody = JSON.parse(updateEp.body);
      assert.equal(parsedBody.name, 'Mechanical Keyboard v2');
      assert.equal(parsedBody.price, 129.99);
      assert.equal(parsedBody.inStock, true);
    });

    it('should safely guard against circular $ref definitions without stack overflow', () => {
      const circularDoc = {
        openapi: '3.0.0',
        info: { title: 'Circular Spec' },
        paths: {
          '/circular': {
            post: {
              summary: 'Circular Endpoint',
              requestBody: {
                content: {
                  'application/json': {
                    schema: { $ref: '#/components/schemas/CircularA' }
                  }
                }
              }
            }
          }
        },
        components: sampleSpringBootDoc.components
      };

      const parsed = openApiParser.parseOpenApi(circularDoc);
      assert.equal(parsed.endpoints.length, 1);
      assert.doesNotThrow(() => JSON.parse(parsed.endpoints[0].body));
    });
  });

  describe('4. Conversion to ApiForge Request Model & {{baseUrl}} Variable Handling', () => {
    it('should convert endpoint using {{baseUrl}} variable by default', () => {
      const parsed = openApiParser.parseOpenApi(sampleSpringBootDoc);
      const listEp = parsed.endpoints.find(e => e.operationId === 'listProducts');

      const req = openApiParser.convertEndpointToRequest(listEp, { useBaseUrlVariable: true });
      assert.equal(req.name, 'List all products with pagination');
      assert.equal(req.method, 'GET');
      assert.equal(req.url, '{{baseUrl}}/api/v1/products');
      assert.equal(req.params.length, 2);
      assert.equal(req.headers.length, 1);
      assert.equal(req.headers[0].key, 'X-Tenant-ID');
      assert.ok(Array.isArray(req.tests));
    });

    it('should convert endpoint using selected server URL when {{baseUrl}} is disabled', () => {
      const parsed = openApiParser.parseOpenApi(sampleSpringBootDoc);
      const listEp = parsed.endpoints.find(e => e.operationId === 'listProducts');

      const req = openApiParser.convertEndpointToRequest(listEp, {
        useBaseUrlVariable: false,
        serverUrl: 'https://api.store.example.com/v1'
      });
      assert.equal(req.url, 'https://api.store.example.com/v1/api/v1/products');
    });

    it('should automatically append Content-Type: application/json for requests with payload', () => {
      const parsed = openApiParser.parseOpenApi(sampleSpringBootDoc);
      const createEp = parsed.endpoints.find(e => e.operationId === 'createProduct');

      const req = openApiParser.convertEndpointToRequest(createEp);
      const ctHeader = req.headers.find(h => h.key.toLowerCase() === 'content-type');
      assert.ok(ctHeader, 'Content-Type header added');
      assert.equal(ctHeader.value, 'application/json');
    });
  });

  describe('5. Collections Integration & Duplicate Handling', () => {
    let testCollectionId = null;

    beforeEach(() => {
      const col = collectionsStorage.createCollection('OpenAPI Import Test Target');
      testCollectionId = col.id;
    });

    afterEach(() => {
      if (testCollectionId) {
        collectionsStorage.deleteCollection(testCollectionId);
        testCollectionId = null;
      }
    });

    it('should save imported requests into collection and handle duplicate rename strategy', () => {
      const parsed = openApiParser.parseOpenApi(sampleSpringBootDoc);
      const endpointsToImport = parsed.endpoints.slice(0, 3);

      // First import
      endpointsToImport.forEach(ep => {
        const req = openApiParser.convertEndpointToRequest(ep);
        collectionsStorage.saveRequest(testCollectionId, null, req, null);
      });

      let updatedCol = collectionsStorage.getCollectionsTree().find(c => c.id === testCollectionId);
      assert.equal(updatedCol.requests.length, 3);

      // Second import with rename
      const duplicateEp = endpointsToImport[0];
      const dupReq = openApiParser.convertEndpointToRequest(duplicateEp);
      dupReq.name = dupReq.name + ' (Imported)';
      collectionsStorage.saveRequest(testCollectionId, null, dupReq, null);

      updatedCol = collectionsStorage.getCollectionsTree().find(c => c.id === testCollectionId);
      assert.equal(updatedCol.requests.length, 4);
      assert.ok(updatedCol.requests.some(r => r.name.includes('(Imported)')));
    });
  });

  describe('6. Local Mock Server HTTP Fetching for /v3/api-docs', () => {
    let mockServer;
    let mockPort;

    beforeEach(async () => {
      await new Promise(resolve => {
        mockServer = http.createServer((req, res) => {
          if (req.url === '/v3/api-docs') {
            res.writeHead(200, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify(sampleSpringBootDoc));
          } else if (req.url === '/invalid-json') {
            res.writeHead(200, { 'Content-Type': 'application/json' });
            res.end('{ invalid: json: syntax');
          } else {
            res.writeHead(404, { 'Content-Type': 'application/json' });
            res.end(JSON.stringify({ error: 'Not Found' }));
          }
        });
        mockServer.listen(0, '127.0.0.1', () => {
          mockPort = mockServer.address().port;
          resolve();
        });
      });
    });

    afterEach(async () => {
      if (mockServer) {
        await new Promise(resolve => mockServer.close(resolve));
      }
    });

    it('should successfully fetch and parse OpenAPI document from local Spring Boot server', async () => {
      const res = await fetch(`http://127.0.0.1:${mockPort}/v3/api-docs`);
      assert.equal(res.status, 200);
      const doc = await res.json();
      const parsed = openApiParser.parseOpenApi(doc);
      assert.equal(parsed.apiInfo.title, 'Spring Boot Store Service');
      assert.ok(parsed.endpoints.length >= 7);
    });

    it('should detect and handle invalid JSON from server response safely', async () => {
      const res = await fetch(`http://127.0.0.1:${mockPort}/invalid-json`);
      const text = await res.text();
      assert.throws(() => JSON.parse(text), /SyntaxError/);
    });
  });
});
