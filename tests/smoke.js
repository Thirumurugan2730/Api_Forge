let mockServer;
let mockPort;

function startMockHttpServer() {
  return new Promise((resolve) => {
    mockServer = http.createServer((req, res) => {
      const parsedUrl = new URL(req.url, `http://${req.headers.host}`);
      let reqBody = '';

      req.on('data', (chunk) => {
        reqBody += chunk.toString();
      });

      req.on('end', () => {
        if (parsedUrl.pathname === '/v3/api-docs') {
          res.writeHead(200, {
            'Content-Type': 'application/json; charset=utf-8',
            'Access-Control-Allow-Origin': '*'
          });
          res.end(JSON.stringify({
            openapi: '3.0.1',
            info: { title: 'Smoke Spring Boot API', version: '1.0.0', description: 'Generated by springdoc-openapi' },
            servers: [{ url: 'http://127.0.0.1:' + mockPort }],
            paths: {
              '/api/smoke-post': {
                post: {
                  summary: 'Smoke Post Endpoint',
                  requestBody: {
                    content: {
                      'application/json': {
                        example: { framework: 'Spring Boot', test: true }
                      }
                    }
                  }
                }
              },
              '/api/smoke-get/{id}': {
                parameters: [{ name: 'id', in: 'path', required: true, schema: { type: 'string' } }],
                get: {
                  summary: 'Smoke Get by ID',
                  parameters: [{ name: 'client', in: 'query', schema: { type: 'string' } }]
                }
              }
            }
          }));
          return;
        }

        if (parsedUrl.pathname === '/api/smoke-role-matrix') {
          const auth = req.headers['authorization'];
          if (auth === 'Bearer smoke-admin-token') {
            res.writeHead(200, { 'Content-Type': 'application/json; charset=utf-8' });
            res.end(JSON.stringify({ status: 'success', role: 'ADMIN', message: 'Admin access granted' }));
          } else if (auth === 'Bearer smoke-user-token') {
            res.writeHead(403, { 'Content-Type': 'application/json; charset=utf-8' });
            res.end(JSON.stringify({ status: 403, error: 'Forbidden', message: 'Access denied: Requires ROLE_ADMIN authority' }));
          } else {
            res.writeHead(401, { 'Content-Type': 'application/json; charset=utf-8', 'WWW-Authenticate': 'Bearer' });
            res.end(JSON.stringify({ status: 401, error: 'Unauthorized', message: 'Full authentication required' }));
          }
          return;
        }

        if (parsedUrl.pathname === '/api/smoke-error-400') {
          res.writeHead(400, {
            'Content-Type': 'application/json; charset=utf-8',
            'Access-Control-Allow-Origin': '*'
          });
          res.end(JSON.stringify({
            timestamp: new Date().toISOString(),
            status: 400,
            error: 'Bad Request',
            message: "Validation failed for object='userDTO'. Error count: 1",
            path: '/api/smoke-error-400',
            errors: [
              {
                field: 'email',
                defaultMessage: 'must be a well-formed email address',
                rejectedValue: 'not-an-email',
                code: 'Email'
              }
            ]
          }));
          return;
        }

        if (parsedUrl.pathname === '/api/smoke-post') {
          res.writeHead(200, {
            'Content-Type': 'application/json; charset=utf-8',
            'X-Response-Echo': 'SmokePostOk',
            'Access-Control-Allow-Origin': '*'
          });
          res.end(
            JSON.stringify({
              status: 'success',
              receivedMethod: req.method,
              receivedQuery: Object.fromEntries(parsedUrl.searchParams.entries()),
              receivedHeader: req.headers['x-smoke-test'] || null,
              receivedBody: reqBody ? JSON.parse(reqBody) : null,
              timestamp: Date.now()
            })
          );
        } else {
          res.writeHead(404, { 'Content-Type': 'application/json' });
          res.end(JSON.stringify({ error: 'Not Found' }));
        }
      });
    });

    mockServer.listen(0, '127.0.0.1', () => {
      mockPort = mockServer.address().port;
      console.log(`[Smoke Test] Mock HTTP Server listening on http://127.0.0.1:${mockPort}`);
      resolve(mockPort);
    });
  });
}

